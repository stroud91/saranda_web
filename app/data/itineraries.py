"""Ready-made itineraries from the planner.

Each day lists ``stops`` in travel order. The first stop is where the day
starts (usually last night's base) and ``overnight`` is where it ends.
"""


def _day(n, title, stops, plan, *, overnight=None, start="08:30", options=()):
    return {
        "day": n,
        "title": title,
        "stops": list(stops),
        "plan": plan,
        "overnight": overnight or stops[-1],
        "start_time": start,
        "options": list(options),
    }


